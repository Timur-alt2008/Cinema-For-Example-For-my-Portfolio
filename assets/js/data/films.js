function build(raw) {
  const today = new Date();
  return raw.map((f) => {
    const premiere = isoDate(addDays(today, f.premiereIn));
    return {
      ...f,
      premiere,
      status: f.premiereIn <= 0 ? 'now' : 'soon',
      genreLabels: f.genres.map((g) => GENRES[g]),
    };
  });
}

